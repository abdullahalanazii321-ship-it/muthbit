'use strict';
const { badRequest } = require('./errors');

const MIN_REASON = 5;
const MAX_REASON = 500;

/**
 * قاعدة واحدة في المنصة كلها: كل فعل يسلب شيئاً من طرف آخر يشترط سبباً مكتوباً.
 *
 * إيقاف مستخدم يلغي طلباته المفتوحة، وإيقاف شركة يوقف موظفيها كلهم،
 * ورفض مورد يسحب عروضه من طلبات قائمة عند شركات أخرى، وسحب عرض يسلب شركةً
 * عرضاً قد تكون بنت عليه قرارها، ورفض طلب يوقف مساراً بدأه غيرك.
 * لا يُترك فعل بهذا الأثر بلا سبب في سجل لا يُعدَّل.
 *
 * ويُفرض هنا لا في الواجهة وحدها: نداء مباشر بلا سبب يُرفض كما يُرفض من الشاشة،
 * وسجل التدقيق لا يفرّق بين النداءين.
 *
 * ولا يُشترط لما يمنح: التوثيق والتفعيل وإعادة التفعيل واعتماد الطلب
 * واختيار العرض وإصدار أمر الشراء. السبب يُطلب لما يسلب لا لما يمنح.
 *
 * يعيد السبب بعد trim — وهو ما يُحفظ، فالمسافات ليست جزءاً من السبب.
 */
function requireReason(raw, message) {
  const reason = typeof raw === 'string' ? raw.trim() : '';
  if (reason.length < MIN_REASON || reason.length > MAX_REASON) throw badRequest(message);
  return reason;
}

module.exports = { MIN_REASON, MAX_REASON, requireReason };
